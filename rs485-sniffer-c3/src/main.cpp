// ─── SETUP ───────────────────────────────────────────────
void setup() {
    pinMode(LED_PIN, OUTPUT);
    pinMode(BOOT_BUTTON, INPUT_PULLUP);
    digitalWrite(LED_PIN, HIGH);

    // RS485 piny — TX HIGH przed begin() żeby nie zaśmiecać magistrali
    pinMode(RS485_TX_PIN, OUTPUT);
    digitalWrite(RS485_TX_PIN, HIGH);
    pinMode(RS485_DE_PIN, OUTPUT);
    digitalWrite(RS485_DE_PIN, LOW);
    pinMode(RS485_RE_PIN, OUTPUT);
    digitalWrite(RS485_RE_PIN, LOW);

    RS485Serial.setRxBufferSize(2048);
    RS485Serial.begin(19200, SERIAL_8E1, RS485_RX_PIN, RS485_TX_PIN);

    // NVS
    prefs.begin("cfg", false);
    bleActive = prefs.getBool("ble", false);
    String wifi_ssid = prefs.getString("ssid", "");
    String wifi_pass = prefs.getString("pass", "");
    prefs.end();

    // WiFi
    WiFi.persistent(false);
    WiFi.disconnect(true);
    delay(100);

    if (wifi_ssid.length() > 0) {
        WiFi.mode(WIFI_STA);
        WiFi.setHostname("rs485-pro-ble");
        WiFi.begin(wifi_ssid.c_str(), wifi_pass.c_str());
        unsigned long t = millis();
        while (WiFi.status() != WL_CONNECTED && millis() - t < 10000) {
            delay(200);
            digitalWrite(LED_PIN, !digitalRead(LED_PIN));
        }
        if (WiFi.status() != WL_CONNECTED) {
            prefs.begin("cfg", false);
            prefs.putString("ssid", "");
            prefs.putString("pass", "");
            prefs.end();
            WiFi.mode(WIFI_AP);
            delay(100);
            WiFi.softAP("RS485_PRO_BLE", "12345678");
            dnsServer.start(53, "*", IPAddress(192,168,4,1));
            apMode = true;
        } else {
            digitalWrite(LED_PIN, LOW);
        }
    } else {
        WiFi.mode(WIFI_AP);
        delay(100);
        WiFi.softAP("RS485_PRO_BLE", "12345678");
        dnsServer.start(53, "*", IPAddress(192,168,4,1));
        apMode = true;
    }

    // mDNS
    if (MDNS.begin("rs485-pro-ble")) {
        MDNS.addService("http", "tcp", 80);
        MDNS.addServiceTxt("http", "tcp", "device", "RS485 Pro BLE");
    }

    // BLE
    if (bleActive) {
        BLEDevice::init("RS485 Pro BLE");
        BLEServer* pSrv = BLEDevice::createServer();
        pSrv->setCallbacks(new MyServerCallbacks());
        BLEService* pSvc = pSrv->createService(SERVICE_UUID);
        pTxCharacteristic = pSvc->createCharacteristic(
            CHARACTERISTIC_UUID_TX, BLECharacteristic::PROPERTY_NOTIFY);
        BLECharacteristic* pRx = pSvc->createCharacteristic(
            CHARACTERISTIC_UUID_RX, BLECharacteristic::PROPERTY_WRITE);
        pRx->setCallbacks(new MyCallbacks());
        pSvc->start();
        BLEDevice::startAdvertising();
    }

    // ─── ROUTES ──────────────────────────────────────────

    server.on("/", HTTP_GET, [](){
        server.sendHeader("Content-Encoding", "gzip");
        server.sendHeader("Cache-Control", "max-age=3600");
        server.setContentLength(index_html_gz_len);
        server.send(200, "text/html", "");
        server.client().write((const char*)index_html_gz, index_html_gz_len);
    });

    server.on("/api/status", HTTP_GET, [](){
        server.sendHeader("Access-Control-Allow-Origin", "*");
        String ip = (WiFi.status() == WL_CONNECTED)
                        ? WiFi.localIP().toString()
                        : WiFi.softAPIP().toString();
        int rssi = (WiFi.status() == WL_CONNECTED) ? WiFi.RSSI() : 0;
        char buf[300];
        snprintf(buf, sizeof(buf),
            "{\"ip\":\"%s\",\"rssi\":%d,\"tx\":%lu,\"rx\":%lu,"
            "\"ble\":%s,\"heap\":%lu,\"sta\":%s,\"mdns\":\"rs485-pro-ble.local\"}",
            ip.c_str(), rssi,
            (unsigned long)txCount, (unsigned long)rxCount,
            bleActive?"true":"false",
            (unsigned long)(ESP.getFreeHeap()/1024),
            (WiFi.status()==WL_CONNECTED)?"true":"false");
        server.send(200, "application/json", buf);
    });

    server.on("/api/send", HTTP_GET, [](){
        if (server.hasArg("msg")) {
            String m = server.arg("msg");
            sendToRS485((const uint8_t*)m.c_str(), m.length());
        }
        server.send(200, "application/json", "{\"ok\":true}");
    });

    // Sniffer polling — działa zawsze, niezależnie od BLE
    server.on("/api/frames", HTTP_GET, [](){
        server.sendHeader("Access-Control-Allow-Origin", "*");
        if (sniffEmpty()) {
            server.send(200, "application/json", "{\"frames\":[]}");
            return;
        }
        String json = "{\"frames\":[";
        bool first = true;
        int maxOut = 16;
        while (!sniffEmpty() && maxOut-- > 0) {
            SniffFrame& f = sniffBuf[sniffTail];
            sniffTail = (sniffTail + 1) % SNIFF_FRAMES;
            if (!first) json += ",";
            first = false;
            String asc = String(f.asc);
            asc.replace("\\", "\\\\");
            asc.replace("\"", "\\\"");
            json += "{\"dir\":\"";
            json += f.dir;
            json += "\",\"ms\":";
            json += f.ms;
            json += ",\"a\":\"";
            json += asc;
            json += "\",\"d\":\"";
            json += f.hex;
            json += "\"}";
        }
        json += "]}";
        server.send(200, "application/json", json);
    });

    server.on("/api/connect", HTTP_GET, [](){
        if (server.hasArg("ssid")) {
            String s = server.arg("ssid");
            String p = server.hasArg("pass") ? server.arg("pass") : "";
            prefs.begin("cfg", false);
            prefs.putString("ssid", s);
            prefs.putString("pass", p);
            prefs.end();
            server.send(200, "application/json", "{\"ok\":true}");
            delay(300); ESP.restart();
        } else {
            server.send(400, "application/json", "{\"ok\":false}");
        }
    });

    server.on("/api/ble", HTTP_GET, [](){
        prefs.begin("cfg", false);
        bool cur = prefs.getBool("ble", false);
        prefs.putBool("ble", !cur);
        prefs.end();
        server.send(200, "application/json", "{\"ok\":true}");
        delay(300); ESP.restart();
    });

    server.on("/api/save", HTTP_GET, [](){
        prefs.begin("cfg", false);
        if (server.hasArg("ble"))
            prefs.putBool("ble", server.arg("ble") == "1");
        prefs.end();
        server.send(200, "application/json", "{\"ok\":true}");
    });

    server.on("/api/reset", HTTP_GET, [](){
        server.send(200, "application/json", "{\"ok\":true}");
        prefs.begin("cfg", false); prefs.clear(); prefs.end();
        delay(300); ESP.restart();
    });

    // Captive portal — Android, iOS, Windows, Firefox, Chrome
    auto redir = [](){
        server.sendHeader("Location", "http://192.168.4.1/");
        server.send(302, "text/plain", "");
    };
    server.on("/generate_204",              HTTP_GET, redir);
    server.on("/gen_204",                   HTTP_GET, redir);
    server.on("/connecttest.txt",           HTTP_GET, redir);
    server.on("/ncsi.txt",                  HTTP_GET, redir);
    server.on("/hotspot-detect.html",       HTTP_GET, redir);
    server.on("/library/test/success.html", HTTP_GET, redir);
    server.on("/success.txt",               HTTP_GET, redir);
    server.on("/canonical.html",            HTTP_GET, redir);

    server.onNotFound([](){
        if (apMode) {
            server.sendHeader("Location", "http://192.168.4.1/");
            server.send(302, "text/plain", "");
        } else {
            server.send(404, "text/plain", "Not found");
        }
    });

    server.begin();
    digitalWrite(LED_PIN, LOW);

    // Logi startowe przez BLE (po 2s żeby klient zdążył się połączyć)
    if (bleActive) {
        delay(2000);
        char buf[80];
        bleLog("[SYS] RS485 Pro BLE start");
        bleLog("[SYS] RS485: 19200/8E1 RE=GPIO3 DE=GPIO2 RX=GPIO4 TX=GPIO1");
        if (WiFi.status() == WL_CONNECTED)
            snprintf(buf, sizeof(buf), "[SYS] WiFi STA: %s", WiFi.localIP().toString().c_str());
        else
            snprintf(buf, sizeof(buf), "[SYS] WiFi AP: RS485_PRO_BLE @ 192.168.4.1");
        bleLog(buf);
        bleLog("[SYS] HTTP OK | rs485-pro-ble.local");
    }
}

// ─── LOOP ────────────────────────────────────────────────
void loop() {
    checkResetButton();
    if (apMode) dnsServer.processNextRequest();
    server.handleClient();

    // RS485 RX — akumulacja z detekcją ciszy
    // USB COM9 jest CICHY — brak Serial.write — GID widzi czyste dane
    while (RS485Serial.available()) {
        uint8_t b = (uint8_t)RS485Serial.read();
        if (frameLen < FRAME_BUF_SIZE) frameBuf[frameLen++] = b;
        lastByteMs  = millis();
        frameActive = true;
    }

    if (frameActive && frameLen > 0 &&
        (millis() - lastByteMs) >= FRAME_IDLE_MS) {
        rxCount++;
        // Sniffer — zawsze aktywny
        sniffPush(frameBuf, frameLen, "RX");
        // BLE notify — tylko gdy aktywne
        if (bleActive && pTxCharacteristic) {
            pTxCharacteristic->setValue(frameBuf, frameLen);
            pTxCharacteristic->notify();
        }
        frameLen    = 0;
        frameActive = false;
    }
}
