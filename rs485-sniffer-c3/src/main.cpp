// ─── RS485 SEND ──────────────────────────────────────────
void sendToRS485(const uint8_t* data, size_t len) {
    if (!len) return;
    digitalWrite(LED_PIN, HIGH);
    digitalWrite(RS485_RE_PIN, HIGH);
    digitalWrite(RS485_DE_PIN, HIGH);
    delayMicroseconds(10);
    RS485Serial.write(data, len);
    RS485Serial.flush();
    delayMicroseconds(100);
    digitalWrite(RS485_DE_PIN, LOW);
    delayMicroseconds(10);
    digitalWrite(RS485_RE_PIN, LOW);
    digitalWrite(LED_PIN, LOW);
    txCount++;
    // Sniffer TX — zawsze aktywny
    sniffPush(data, len, "TX");
    // BLE notify — tylko gdy aktywne
    if (bleActive && pTxCharacteristic) {
        pTxCharacteristic->setValue((uint8_t*)data, len);
        pTxCharacteristic->notify();
    }
}

// ─── BLE LOG ─────────────────────────────────────────────
void bleLog(const char* msg) {
    if (!bleActive || !pTxCharacteristic) return;
    pTxCharacteristic->setValue((uint8_t*)msg, strlen(msg));
    pTxCharacteristic->notify();
    delay(20);
}

// ─── RESET BUTTON ────────────────────────────────────────
void checkResetButton() {
    if (digitalRead(BOOT_BUTTON) != LOW) return;
    unsigned long t = millis();
    while (digitalRead(BOOT_BUTTON) == LOW) {
        if (millis() - t > 5000) {
            for (int i=0;i<10;i++){
                digitalWrite(LED_PIN,HIGH);delay(100);
                digitalWrite(LED_PIN,LOW);delay(100);
            }
            prefs.begin("cfg", false);
            prefs.clear();
            prefs.end();
            delay(300);
            ESP.restart();
        }
    }
}

