// ─── SNIFFER RING BUFFER ─────────────────────────────────
#define SNIFF_FRAMES 32
struct SniffFrame {
    char     hex[FRAME_BUF_SIZE * 3 + 4];
    char     asc[FRAME_BUF_SIZE + 4];
    char     dir[3];
    uint32_t ms;
};
static SniffFrame sniffBuf[SNIFF_FRAMES];
static uint8_t sniffHead = 0;
static uint8_t sniffTail = 0;
static bool sniffEmpty() { return sniffHead == sniffTail; }
static bool sniffFull()  { return ((sniffHead+1) % SNIFF_FRAMES) == sniffTail; }

void sniffPush(const uint8_t* buf, size_t len, const char* dir) {
    if (!len || sniffFull()) return;
    SniffFrame& f = sniffBuf[sniffHead];
    int p = 0;
    for (size_t i = 0; i < len && i < FRAME_BUF_SIZE; i++) {
        if (i) f.hex[p++] = ' ';
        snprintf(f.hex + p, 4, "%02X", buf[i]);
        p += 2;
    }
    f.hex[p] = '\0';
    for (size_t i = 0; i < len && i < FRAME_BUF_SIZE; i++)
        f.asc[i] = (buf[i] >= 0x20 && buf[i] < 0x7F) ? (char)buf[i] : '.';
    f.asc[len < FRAME_BUF_SIZE ? len : FRAME_BUF_SIZE] = '\0';
    strncpy(f.dir, dir, 2); f.dir[2] = '\0';
    f.ms = millis();
    sniffHead = (sniffHead + 1) % SNIFF_FRAMES;
}

